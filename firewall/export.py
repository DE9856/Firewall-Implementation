"""Session exports: blocked packets as a pcap file (opens in Wireshark or
tcpdump -r), and a plain-text session report in Markdown."""

from __future__ import annotations

import struct
import time
from collections import Counter

LINKTYPE_RAW = 101          # packets start at the IP header, as PyWall receives them


def pcap(records: list[dict]) -> bytes:
    """Classic pcap of the recorded packets. PyWall keeps each packet's headers only
    (up to 60 bytes), so every frame is marked as truncated: captured length < length."""
    out = [struct.pack("<IHHiIII", 0xA1B2C3D4, 2, 4, 0, 0, 65535, LINKTYPE_RAW)]
    for r in records:
        data = bytes.fromhex(r.get("header") or "")
        if not data:
            continue
        sec = int(r["t"])
        out.append(struct.pack("<IIII", sec, int((r["t"] - sec) * 1e6), len(data), max(len(data), r.get("len") or 0)))
        out.append(data)
    return b"".join(out)


def _when(t: float) -> str:
    return time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(t))


def report(snap: dict, findings: dict) -> str:
    """A readable summary of the session, from a dashboard snapshot."""
    s, cfg, src = snap["stats"], snap["config"], snap["source"]
    held = snap.get("held", [])
    lines = [
        "# PyWall session report", "",
        f"- Generated: {_when(snap['now'])}",
        f"- Running since: {_when(snap['started'])}",
        f"- Traffic source: {src['label']}",
        f"- Default policy: {cfg['defaultPolicy']}; stateful: {'on' if cfg['stateful'] else 'off'}; "
        f"local networks: {', '.join(cfg['localNetworks']) or 'none'}",
        "", "## Totals", "",
        "| Packets checked | Allowed | Blocked | Open connections | Active bans |",
        "| ---: | ---: | ---: | ---: | ---: |",
        f"| {s['total']:,} | {s['accepted']:,} | {s['dropped']:,} | {s['connections']:,} | {s['bans']} |",
        "", "### Where blocked packets were stopped", "",
        "| Stage | Packets |", "| --- | ---: |",
    ]
    labels = {"parse": "Parse (malformed)", "whitelist": "Whitelist", "blacklist": "Blacklist",
              "ids_ban": "IDS ban list", "ids": "IDS detectors", "conntrack": "Connection tracking (invalid)",
              "rule": "Rule table", "policy": "Default policy"}
    for stage, n in sorted(s["byStage"].items(), key=lambda kv: -kv[1]):
        lines.append(f"| {labels.get(stage, stage)} | {n:,} |")

    by_src = Counter(p["src"] for p in held if p.get("src"))
    if by_src:
        lines += ["", "## Most-blocked sources", "", "| Source | Blocked packets | Last reason |", "| --- | ---: | --- |"]
        last = {p["src"]: p["reason"] for p in held if p.get("src")}
        for ip, n in by_src.most_common(10):
            lines.append(f"| `{ip}` | {n:,} | {last[ip]} |")

    alerts = [e for e in snap["events"] if e["kind"] == "ids" and e["severity"] == "critical"]
    lines += ["", "## Intrusion detection", ""]
    if alerts:
        lines += ["| Time | Source | Detection |", "| --- | --- | --- |"]
        lines += [f"| {_when(e['first'])} | `{e['src']}` | {e['detail']} |" for e in alerts[-30:]]
    else:
        lines.append("No SYN floods, port scans or ping floods were detected.")

    lines += ["", "## Rule table", "", "| # | Rule | Action | Matches | Note |", "| ---: | --- | --- | ---: | --- |"]
    for r in snap["rules"]:
        name = r["spec"].get("name") or f"rule {r['id']}"
        f = findings.get(r["id"])
        note = ("disabled" if not r["enabled"] else f"{f['kind']}: covered by rule {f['by']}" if f and f["by"]
                else f["kind"] if f else "never matched" if not r["hits"] else "")
        lines.append(f"| {r['position']} | {name} (#{r['id']}) | {r['spec']['action']} | {r['hits']:,} | {note} |")

    config_events = [e for e in snap["events"] if e["kind"] == "config"]
    if config_events:
        lines += ["", "## Configuration changes", ""]
        lines += [f"- {_when(e['first'])}: {e['title']}. {e['detail']}" for e in config_events]
    lines += ["", "---", "Generated by PyWall. Counts cover this session; blocked-packet lists cover the "
              f"{len(held):,} most recent blocked packets kept in memory.", ""]
    return "\n".join(lines)
